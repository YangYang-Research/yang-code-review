test('buildSarif uses Dependabot-like titles and help.markdown', () => {
  const sarif = buildSarif({
    findings: parseFindings(SAMPLE),
    reportText: SAMPLE,
    owner: 'acme',
    repo: 'app',
    commitSha: 'abc123'
  });
  const result = sarif.runs[0].results[0];
  const rule = sarif.runs[0].tool.driver.rules[0];
  assert.equal(result.ruleId, 'ycr-sql-injection');
  assert.match(result.message.text, /^High severity - SQL Injection/);
  assert.match(rule.help.markdown, /## Overview/);
  assert.match(rule.help.markdown, /## Remediation/);
  assert.ok(rule.properties.tags.includes('severity/high'));
  assert.equal(rule.properties['security-severity'], '8.0');
});

test('help.markdown includes Proof of concept and Code fix', () => {
  const sarif = buildSarif({
    findings: [
      {
        severity: 'HIGH',
        title: 'XSS',
        description: 'Reflected XSS',
        impact: 'Session theft',
        poc: "GET /?q=<script>alert(1)</script>",
        recommendation: 'Encode output',
        fix: "res.send(escapeHtml(q))",
        owasp: 'A03:2021',
        file: 'src/app.js',
        line: 10
      }
    ],
    reportText: '',
    owner: 'acme',
    repo: 'app',
    commitSha: 'abc'
  });
  const md = sarif.runs[0].tool.driver.rules[0].help.markdown;
  assert.match(md, /## Proof of concept/);
  assert.match(md, /alert\(1\)/);
  assert.match(md, /## Remediation/);
  assert.match(md, /### Code fix/);
  assert.match(md, /escapeHtml/);
});

test('buildSarif falls back when no structured findings', () => {
  const sarif = buildSarif({
    findings: [],
    reportText: 'plain prose only',
    owner: 'acme',
    repo: 'app',
    commitSha: 'abc',
    fallbackUri: 'README.md'
  });
  const result = sarif.runs[0].results[0];
  assert.equal(result.ruleId, 'ycr-report');
  assert.equal(
    result.locations[0].physicalLocation.artifactLocation.uri,
    'README.md'
  );
  assert.match(sarif.runs[0].tool.driver.rules[0].help.markdown, /## Overview/);
});

test('formatDependabotStyleComment builds summary table', () => {
  const md = formatDependabotStyleComment(parseFindings(SAMPLE));
  assert.match(md, /Detected \*\*2\*\* vulnerabilities/);
  assert.match(md, /\| Severity \| Title \| Location \|/);
  assert.match(md, /SQL Injection/);
  assert.match(md, /<details>/);
});

test('resolveFindingPath prefers existing workspace file', () => {
  assert.equal(
    resolveFindingPath('index.js', (p) => p === 'src/index.js'),
    'src/index.js'
  );
  assert.equal(
    resolveFindingPath('src/db.js', (p) => p === 'src/db.js'),
    'src/db.js'
  );
});

test('artifact name uses date and optional PR id', () => {
  assert.equal(
    buildArtifactName({date: '2026-10-11', pullNumber: 42}),
    'yang-code-review-report-2026-10-11-pr-42'
  );
  assert.equal(
    buildArtifactName({date: '2026-10-11'}),
    'yang-code-review-report-2026-10-11'
  );
  assert.match(reportDateStamp(new Date('2026-10-11T12:00:00Z')), /2026-10-11/);
});
