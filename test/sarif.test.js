import assert from 'node:assert/strict';
import test from 'node:test';

import {
  buildArtifactName,
  buildSarif,
  formatDependabotStyleComment,
  parseFindings,
  reportDateStamp,
  resolveFindingPath
} from '../src/sarif.js';

const SAMPLE = `
**Detailed Findings:**

[HIGH] SQL Injection
OWASP: A03:2021 Injection
Location: src/db.js:42
E2E Flow: login
Change/Source: req.body.q
Sink: db.query
Description: User input reaches raw SQL.
Impact: Data leak
Recommendation: Use parameterized queries
Code Example: db.query('select 1')

[MEDIUM] Missing authz
OWASP: API1:2023
Location: src/api/user.ts:10
Description: IDOR on user endpoint.
Recommendation: Check ownership

### Report Generated by Yang Code Review (YCR) - YangYang Organization
`;

const BULLET_SAMPLE = `
**Findings**

Here are the findings for the identified flow:

* **Vulnerability Type:** Insecure Dependency Update (OWASP Web Top 10, A3)
* **OWASP Catalog Item:** A3 - Insecure Dependencies
* **Location:** \`index.js\` (specifically, the \`buildSarif\` function)
* **E2E Flow:** The \`buildSarif\` function is called
* **Change/Source:** tool version bump
* **Sink:** analysis pipeline
* **Description:** Updated tool version may introduce a vulnerability.
* **Impact:** Attacker may compromise the project.
* **Recommendation:** Pin and audit the tool version.
`;

test('parseFindings extracts severity location and text', () => {
  const findings = parseFindings(SAMPLE);
  assert.equal(findings.length, 2);
  assert.equal(findings[0].severity, 'HIGH');
  assert.equal(findings[0].title, 'SQL Injection');
  assert.equal(findings[0].file, 'src/db.js');
  assert.equal(findings[0].line, 42);
  assert.equal(findings[1].severity, 'MEDIUM');
  assert.equal(findings[1].file, 'src/api/user.ts');
});

const BOLD_SAMPLE = `
**Detailed Findings:**

**MEDIUM ReDoS Vulnerability in Regex Parsing**
OWASP: N/A (General Secure Coding)
Location: \`src/sarif.js:parseLocation\`
E2E Flow: SARIF Report Generation
Change/Source: User-provided report content
Sink: Regex processing in \`parseLocation\`
Description: The regex is vulnerable to ReDoS.
Impact: Attackers could trigger DoS.
Recommendation: Use a safer regex.

**MEDIUM Path Traversal Risk in File Resolution**
OWASP: OWASP Web Top 10 A4
Location: \`src/sarif.js:resolveFindingPath\`
Description: Path resolution lacks sanitization.
Impact: Arbitrary file read.
Recommendation: Reject \`..\`.

### Report Generated by Yang Code Review (YCR) - YangYang Organization
`;

test('parseFindings understands **MEDIUM Title** blocks', () => {
  const findings = parseFindings(BOLD_SAMPLE);
  assert.equal(findings.length, 2);
  assert.equal(findings[0].severity, 'MEDIUM');
  assert.equal(findings[0].title, 'ReDoS Vulnerability in Regex Parsing');
  assert.equal(findings[0].file, 'src/sarif.js');
  assert.equal(findings[0].line, undefined);
  assert.equal(findings[1].file, 'src/sarif.js');
});

test('parseFindings understands bullet Dependabot-ish blocks', () => {
  const findings = parseFindings(BULLET_SAMPLE);
  assert.equal(findings.length, 1);
  assert.equal(findings[0].title, 'Insecure Dependency Update');
  assert.match(findings[0].owasp, /A3/);
  assert.equal(findings[0].file, 'index.js');
  assert.equal(findings[0].severity, 'MEDIUM');
});

test('buildSarif uses Dependabot-like titles and help.markdown', () => {
  const sarif = buildSarif({
    findings: parseFindings(SAMPLE),
    reportText: SAMPLE,
    owner: 'acme',
    repo: 'app',
    commitSha: 'abc123'
  });
  const result = sarif.runs[0].results[0];
  const rule = sarif.runs[0].tool.driver.rules[0];
  assert.equal(result.ruleId, 'ycr-sql-injection');
  assert.match(result.message.text, /^High severity - SQL Injection/);
  assert.match(rule.help.markdown, /## Overview/);
  assert.match(rule.help.markdown, /## Remediation/);
  assert.ok(rule.properties.tags.includes('severity/high'));
  assert.equal(rule.properties['security-severity'], '8.0');
});

test('buildSarif falls back when no structured findings', () => {
  const sarif = buildSarif({
    findings: [],
    reportText: 'plain prose only',
    owner: 'acme',
    repo: 'app',
    commitSha: 'abc',
    fallbackUri: 'README.md'
  });
  const result = sarif.runs[0].results[0];
  assert.equal(result.ruleId, 'ycr-report');
  assert.equal(
    result.locations[0].physicalLocation.artifactLocation.uri,
    'README.md'
  );
  assert.match(sarif.runs[0].tool.driver.rules[0].help.markdown, /## Overview/);
});

test('formatDependabotStyleComment builds summary table', () => {
  const md = formatDependabotStyleComment(parseFindings(SAMPLE));
  assert.match(md, /Detected \*\*2\*\* vulnerabilities/);
  assert.match(md, /\| Severity \| Title \| Location \|/);
  assert.match(md, /SQL Injection/);
  assert.match(md, /<details>/);
});

test('resolveFindingPath prefers existing workspace file', () => {
  assert.equal(
    resolveFindingPath('index.js', (p) => p === 'src/index.js'),
    'src/index.js'
  );
  assert.equal(
    resolveFindingPath('src/db.js', (p) => p === 'src/db.js'),
    'src/db.js'
  );
});

test('artifact name uses date and optional PR id', () => {
  assert.equal(
    buildArtifactName({date: '2026-10-11', pullNumber: 42}),
    'yang-code-review-report-2026-10-11-pr-42'
  );
  assert.equal(
    buildArtifactName({date: '2026-10-11'}),
    'yang-code-review-report-2026-10-11'
  );
  assert.match(reportDateStamp(new Date('2026-10-11T12:00:00Z')), /2026-10-11/);
});
