test('parseJsonFindings reads ycr-findings fence', () => {
  const report = `
Narrative...

\`\`\`ycr-findings
[
  {
    "severity": "HIGH",
    "title": "SQL Injection",
    "file": "src/db.js",
    "line": 42,
    "owasp": "A03:2021",
    "description": "User input in SQL",
    "impact": "Data leak",
    "poc": "GET /search?q=1'+OR+'1'='1",
    "recommendation": "Use binds",
    "fix": "db.query('select 1 where id=$1', [id])",
    "source": "req.body.q",
    "sink": "db.query"
  }
]
\`\`\`
`;
  const findings = parseJsonFindings(report);
  assert.equal(findings.length, 1);
  assert.equal(findings[0].severity, 'HIGH');
  assert.equal(findings[0].file, 'src/db.js');
  assert.equal(findings[0].line, 42);
  assert.match(findings[0].poc, /OR/);
  assert.match(findings[0].fix, /\$1/);
  assert.equal(parseFindings(report)[0].title, 'SQL Injection');
});

test('parseFindings extracts severity location and text', () => {
  const findings = parseFindings(SAMPLE);
  assert.equal(findings.length, 2);
  assert.equal(findings[0].severity, 'HIGH');
  assert.equal(findings[0].title, 'SQL Injection');
  assert.equal(findings[0].file, 'src/db.js');
  assert.equal(findings[0].line, 42);
  assert.equal(findings[1].severity, 'MEDIUM');
  assert.equal(findings[1].file, 'src/api/user.ts');
});

